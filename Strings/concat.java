package src.main.java.JavaBasic.Strings;

/**
 * Demonstrates string concatenation in Java.
 */
public class concat {
    public static void main(String[] args) {
        // Define variables with meaningful names
        String firstName = "Abhijeet";
        String lastName = "Jha";

        // Concatenate strings with a space
        String fullName = firstName + " " + lastName;

        // Print the full name with a message
        System.out.println("Full Name: " + fullName);
    }
}
